let keyPromise: Promise<CryptoKey> | null = null;

async function communityKey(): Promise<CryptoKey> {
  if (!keyPromise) {
    keyPromise = (async () => {
      const parts = SEED_PARTS.map((p) => new TextEncoder().encode(p));
      const total = parts.reduce((n, p) => n + p.length, 0);
      const merged = new Uint8Array(total);
      let offset = 0;
      for (const part of parts) {
        merged.set(part, offset);
        offset += part.length;
      }
      const hash = await crypto.subtle.digest("SHA-256", merged);
      return crypto.subtle.importKey("raw", hash, { name: "AES-GCM" }, false, ["decrypt"]);
    })();
  }
  return keyPromise;
}

async function decryptCommunityUrl(kind: keyof typeof URLS): Promise<string | null> {
  try {
    const key = await communityKey();
    const { nonce, ciphertext, tag } = URLS[kind];
    const sealed = new Uint8Array(ciphertext.length + tag.length);
    sealed.set(ciphertext);
    sealed.set(tag, ciphertext.length);
    const plain = await crypto.subtle.decrypt({ name: "AES-GCM", iv: nonce, additionalData: AAD }, key, sealed);
    return new TextDecoder().decode(plain);
  } catch {
    return null;
  }
}

export async function getCommunityDownloadUrl(kind: keyof typeof URLS): Promise<string | null> {
  const base = await decryptCommunityUrl(kind);
  if (!base) return null;
  return `${base.replace(/\/$/, "")}/api/dl`;
}
